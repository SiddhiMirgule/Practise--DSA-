package com.siddhi;
import java.util.*;
public class Conditional {
    public static void main(String[] args) {
        int x = 15;

        if (x > 10) {
            System.out.println("A");
        }
        else if (x > 12) {
            System.out.println("B");
        }
        if (x > 20) {
            System.out.println("C");
        }
        System.out.println("D");
    }
}
